import AppKit
import SwiftUI

struct ClipEntry: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image }

    let id: UUID
    var kind: Kind
    var text: String?
    var imageFile: String?
    var date: Date
    var appBundleID: String?
}

/// Merkt sich alles, was mit ⌘C kopiert wird (Text & Bilder).
final class ClipboardHistory: ObservableObject {
    @Published private(set) var entries: [ClipEntry] = []

    private let maxEntries = 60
    private let maxImageBytes = 15_000_000
    private let indexURL = AppPaths.root.appendingPathComponent("history.json")
    private let pasteboard = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    private let ioQueue = DispatchQueue(label: "nodge.history.io", qos: .utility)

    /// Passwort-Manager markieren sensible Inhalte so – die speichern wir nie.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        lastChange = pasteboard.changeCount
        load()
    }

    /// Nur für Vorschau-Snapshots
    init(preview: [ClipEntry]) {
        lastChange = pasteboard.changeCount
        entries = preview
    }

    func start() {
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.25 // erlaubt macOS, Aufweckvorgänge zu bündeln
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func imageURL(for entry: ClipEntry) -> URL? {
        entry.imageFile.map { AppPaths.history.appendingPathComponent($0) }
    }

    // MARK: - Aufzeichnen

    private func poll() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard AppSettings.shared.recordClipboard else { return }

        let types = pasteboard.types ?? []
        if types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }
        // In Finder kopierte Dateien liegen ohnehin auf der Platte
        if types.contains(.fileURL) { return }

        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let s = pasteboard.string(forType: .string),
           !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            addText(s, app: app)
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
                  data.count < maxImageBytes {
            addImage(data, app: app)
        }
    }

    private func addText(_ text: String, app: String?) {
        if let existing = entries.firstIndex(where: { $0.kind == .text && $0.text == text }) {
            var entry = entries[existing]
            entry.date = Date()
            entry.appBundleID = app ?? entry.appBundleID
            withAnimation(.spring(response: 0.4, dampingFraction: 0.8)) {
                entries.remove(at: existing)
                entries.insert(entry, at: 0)
            }
        } else {
            insert(ClipEntry(id: UUID(), kind: .text, text: text, date: Date(), appBundleID: app))
        }
        save()
    }

    private func addImage(_ data: Data, app: String?) {
        guard let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) else { return }
        let id = UUID()
        let name = "\(id.uuidString).png"
        do { try png.write(to: AppPaths.history.appendingPathComponent(name)) } catch { return }
        insert(ClipEntry(id: id, kind: .image, imageFile: name, date: Date(), appBundleID: app))
        save()
    }

    private func insert(_ entry: ClipEntry) {
        withAnimation(.spring(response: 0.4, dampingFraction: 0.8)) {
            entries.insert(entry, at: 0)
            while entries.count > maxEntries {
                deleteStorage(of: entries.removeLast())
            }
        }
    }

    // MARK: - Aktionen

    func copy(_ entry: ClipEntry) {
        pasteboard.clearContents()
        switch entry.kind {
        case .text:
            pasteboard.setString(entry.text ?? "", forType: .string)
        case .image:
            if let url = imageURL(for: entry), let image = NSImage(contentsOf: url) {
                pasteboard.writeObjects([image])
            }
        }
        // Eintrag nach vorne holen
        if let index = entries.firstIndex(of: entry) {
            var moved = entries[index]
            moved.date = Date()
            withAnimation(.spring(response: 0.4, dampingFraction: 0.8)) {
                entries.remove(at: index)
                entries.insert(moved, at: 0)
            }
            save()
        }
        lastChange = pasteboard.changeCount
    }

    func moveToShelf(_ entry: ClipEntry, shelf: ShelfStore) {
        switch entry.kind {
        case .text:
            if let text = entry.text { shelf.ingest([ShelfStore.webURL(from: text).map { .link($0) } ?? .text(text)]) }
        case .image:
            if let url = imageURL(for: entry), let data = try? Data(contentsOf: url) { shelf.ingest([.image(data)]) }
        }
    }

    func dragProvider(for entry: ClipEntry) -> NSItemProvider {
        switch entry.kind {
        case .text:
            return NSItemProvider(object: (entry.text ?? "") as NSString)
        case .image:
            guard let url = imageURL(for: entry), let image = NSImage(contentsOf: url) else { return NSItemProvider() }
            return NSItemProvider(object: image)
        }
    }

    func remove(_ entry: ClipEntry) {
        withAnimation(.spring(response: 0.35, dampingFraction: 0.8)) {
            entries.removeAll { $0.id == entry.id }
        }
        deleteStorage(of: entry)
        save()
    }

    func removeAll() {
        let old = entries
        withAnimation(.spring(response: 0.35, dampingFraction: 0.85)) { entries.removeAll() }
        old.forEach(deleteStorage)
        save()
    }

    // MARK: - Persistenz

    private func deleteStorage(of entry: ClipEntry) {
        if let url = imageURL(for: entry) { try? FileManager.default.removeItem(at: url) }
    }

    private func load() {
        guard let data = try? Data(contentsOf: indexURL),
              let decoded = try? JSONDecoder().decode([ClipEntry].self, from: data) else { return }
        entries = decoded
    }

    private func save() {
        let snapshot = entries
        let url = indexURL
        ioQueue.async {
            if let data = try? JSONEncoder().encode(snapshot) { try? data.write(to: url, options: .atomic) }
        }
    }
}
